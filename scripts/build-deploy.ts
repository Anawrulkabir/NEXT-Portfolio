#!/usr/bin/env tsx
/**
 * Builds the home page's deploy experience from its sources in
 * src/components/deploy/source:
 *   - the six section files → engine.js (one mountDeploy function)
 *   - shell.html's <style>  → deploy.css, scoped to .x so other routes keep their look
 *   - shell.html's markup   → shell.ts
 * Run `npm run build:deploy` after editing a source file; the outputs are committed.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const DIR = join(process.cwd(), 'src/components/deploy')
const SRC = join(DIR, 'source')
const PARTS = ['1-core.js', '2-scene.js', '3-sound.js', '4-term.js', '6-devices.js', '5-ui.js']

/** Replace the first occurrence, and fail loudly if the anchor is gone. */
function swap(s: string, from: string, to: string): string {
  if (!s.includes(from)) throw new Error(`build-deploy: anchor not found: ${from.slice(0, 60)}`)
  return s.replace(from, () => to)
}

let body = PARTS.map((f) => readFileSync(join(SRC, f), 'utf8') + '\n').join('')
// three r169: keep the colours exactly as authored (no colour management), as in the prototype
body = swap(
  body,
  'const renderer = new THREE.WebGLRenderer({ canvas, antialias: true });',
  'const renderer = new THREE.WebGLRenderer({ canvas, antialias: true });\nif ("outputColorSpace" in renderer) renderer.outputColorSpace = THREE.LinearSRGBColorSpace;',
)
const engine =
  '/* eslint-disable */\n// @ts-nocheck\n' +
  '/**\n * fahad-kabir.yaml — the portfolio as a deployment. Generated by scripts/build-deploy.ts from\n' +
  ' * src/components/deploy/source; edit those files, not this one.\n' +
  ' * mountDeploy(THREE, HLIB, ROOT, IMG): three, @lucasmarkes/hairline, the shell element, image URLs.\n */\n' +
  'export function mountDeploy(THREE, HLIB, ROOT, IMG) {\n' +
  'if (THREE.ColorManagement) THREE.ColorManagement.enabled = false;\n' +
  body +
  'return API;\n}\n'
writeFileSync(join(DIR, 'engine.js'), engine)

const shell = readFileSync(join(SRC, 'shell.html'), 'utf8')
let style = shell.slice(shell.indexOf('<style>') + 7, shell.indexOf('</style>'))
let markup = shell.slice(shell.indexOf('<div class="x" data-x>'), shell.indexOf('<script src=')).trim()
markup = markup.replaceAll('__PORTRAIT__', '/media/portrait/fahad-2026.webp')

// scope the page-wide rules to this experience, so other routes keep their own look
style = swap(style, ':root {', '.x {')
style = swap(style, ':root:not([data-theme="light"]) {', ':root:not([data-theme="light"]) .x {')
style = swap(style, ':root[data-theme="dark"] {', ':root[data-theme="dark"] .x {')
style = swap(style, 'html, body { height: 100%; }\nbody {', 'body:has(.x) {')
style = swap(style, '* { box-sizing: border-box; }', '.x, .x * { box-sizing: border-box; }')
// element resets go through :where() so they weigh no more than one class, and the class rules after them win
for (const sel of ['button', 'a', 'h1, h2, h3, h4, p, ul, ol, dl, dd', 'ul, ol', 'em']) {
  style = swap(style, `\n${sel} {`, `\n.x :where(${sel}) {`)
}
style = swap(style, '\n:is(button, a, input, canvas):focus-visible {', '\n.x :is(button, a, input, canvas):focus-visible {')
// the site's layout sets its own font on body; the experience sets its type on its root
style = swap(
  style,
  'body:has(.x) {',
  '.x { color: var(--ink); font: 400 13px/1.55 var(--sans); -webkit-font-smoothing: antialiased; }\nbody:has(.x) {',
)

const css =
  "@import url('https://fonts.googleapis.com/css2?family=Geist:wght@400;500;600&family=Geist+Mono:wght@400;500&family=Instrument+Serif:ital@0;1&display=swap');\n" +
  '/* fahad-kabir.yaml — styles for the deploy experience (generated by scripts/build-deploy.ts) */\n' +
  style.trim() +
  '\n'
writeFileSync(join(DIR, 'deploy.css'), css)
writeFileSync(
  join(DIR, 'shell.ts'),
  "/** The experience's interface layers; the engine finds its parts by their data attributes. Generated. */\nexport const SHELL = " +
    JSON.stringify(markup) +
    '\n',
)
console.log(`build-deploy: engine ${Math.round(engine.length / 1024)} KB, css ${Math.round(css.length / 1024)} KB`)
